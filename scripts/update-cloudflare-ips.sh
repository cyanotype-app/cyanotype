#!/usr/bin/env bash
# Regenerate infra/caddy/cloudflare-ips.caddy from Cloudflare's published ranges.
# Review the diff, commit, and redeploy (or `docker compose ... restart gateway`).
set -euo pipefail
out="$(dirname "$0")/../infra/caddy/cloudflare-ips.caddy"
v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
[ -n "$v4" ] && [ -n "$v6" ] || { echo "empty response" >&2; exit 1; }
{
  echo "# Cloudflare edge ranges (https://www.cloudflare.com/ips). Generated by scripts/update-cloudflare-ips.sh on $(date -u +%F)."
  echo "# Imported inside the global "servers" block by tls/cloudflare-origin/servers.caddy."
  echo "trusted_proxies static \\"
  printf '%s\n%s\n' "$v4" "$v6" | sed 's/^/\t/; s/$/ \\/' | sed '$ s/ \\$//'
} > "$out"
echo "wrote $out"
